// @ts-check
import assert from 'node:assert/strict';
import process from 'node:process';

let path = process.argv[2];
console.log("Loading asar from", path);
/** @type {import("../dll-bindings/asar.d.ts").AsarInterface} */
let Asar = await (await import(path)).default();

assert(Asar.version() >= 20000);
assert.equal(Asar.apiversion(), 400);

// in general we want to do two of everything to make sure the struct sizes
// are correct
var {ok, rom_data} = Asar.patch({
	patch_name: "/a.asm",
	rom_data: new Uint8Array(),
	additional_defines: {"somedefine": "a", "define2": "x"},
	memory_files: {
		"/a.asm": `
org $8000
  lda #0
org $1ffff
  db 0
org $018000
lbl:
  db 0
lbl2:

; make generate_checksum actually do something
norom

macro x(a)
  incsrc "/b.asm"
  print "<a>"
endmacro
macro y(h)
  %x(<h>)
endmacro
%y(a)
%y(b)
!x = asdf
!y := !somedefine
`,
		"/b.asm": '\nwarn "hello <a>!"',
	},
	generate_checksum: true,
	full_call_stack: true,
	warning_overrides: {
		"Wspanish_inquisition": false,
		"Wimplicitly_sized_immediate": true,
	}
});

assert(ok);
assert.deepEqual(Asar.geterrors(), []);
assert.deepEqual(Asar.getprints(), ['a', 'b']);

let warns = Asar.getwarnings();
assert.deepEqual(warns.map(w => w.errname),
	['Winvalid_warning_id', 'Wimplicitly_sized_immediate',
	 'Wwarn_command', 'Wwarn_command']);

assert.deepEqual(warns[3], {
  fullerrdata: 'b.asm:2: warning: (Wwarn_command): warn command: hello b!\n' +
    '    in block: [warn "hello b!"]\n' +
    'Full call stack:\n' +
    '|   2:   a.asm:15\n' +
    '|            in block: [incsrc "/b.asm"]\n' +
    '|   1:   a.asm:19\n' +
    '|            in macro call: [%x(b)]\n' +
    '|   0:   a.asm:22\n' +
    '|            in macro call: [%y(b)]',
  rawerrdata: 'warn command: hello b!',
  block: 'warn "hello b!"',
  filename: '/b.asm',
  line: 1,
  callstack: [
    { fullpath: '/a.asm', prettypath: 'a.asm', lineno: 21,
      details: '\nin macro call: [%y(b)]' },
    { fullpath: '/a.asm', prettypath: 'a.asm', lineno: 18,
      details: '\nin macro call: [%x(b)]' },
    { fullpath: '/a.asm', prettypath: 'a.asm', lineno: 14,
      details: '\nin block: [incsrc "/b.asm"]' }
  ],
  errname: 'Wwarn_command'
});

assert.deepEqual(Asar.getalllabels(), { "lbl": 0x18000, "lbl2": 0x18001 });
assert.equal(Asar.getlabelval("lbl"), 0x18000);
assert.equal(Asar.getlabelval("lbl3"), null);

assert.deepEqual(Asar.getalldefines(), {
	assembler: 'asar',
	assembler_time: Asar.getdefine("assembler_time"),
	assembler_ver: ""+Asar.version(),
	define2: 'x',
	somedefine: 'a',
	x: 'asdf',
	y: 'a',
});
assert.equal(Asar.getdefine("bghfdgfdw"), "");
assert.equal(Asar.resolvedefines("aa!{!define2}"), "aaasdf");
assert.equal(Asar.resolvedefines("aa!{!define3}"), "");

assert.equal(Asar.getmapper(), "norom");

assert.deepEqual(Asar.getwrittenblocks(), [
	{ pcoffset: 0xffdc, snesoffset: 0xffdc, numbytes: 4 },
	{ pcoffset: 0, snesoffset: 0x808000, numbytes: 2 },
	{ pcoffset: 0x8000, snesoffset: 0x818000, numbytes: 1 },
	{ pcoffset: 0xffff, snesoffset: 0x81ffff, numbytes: 1 },
]);

assert.equal(Asar.getsymbolsfile("wla"),
`; wla symbolic information file
; generated by asar

[labels]
01:8000 lbl
01:8001 lbl2

[source files]
0000 42883631 /a.asm

[rom checksum]
210fc602

[addr-to-line mapping]
00:8000 0000:00000003
01:ffff 0000:00000005
01:8000 0000:00000008
`);

assert.deepEqual(Asar.math("2+2"), [4, null]);
assert.deepEqual(Asar.math("lbl"), [0x018000, null]);
assert.deepEqual(Asar.math("aaaaaaa"), [null, "Label 'aaaaaaa' wasn't found."]);

// ---------------------------

var {ok, rom_data} = Asar.patch({
	patch_name: "/a.asm",
	rom_data: new Uint8Array([1,2,3,4]),
	include_paths: ["/a", "/b"],
	memory_files: {
		"/a.asm": `
org $8001
db 5
incbin "b.bin"
incbin "c.bin"
incbin "d.bin"
`,
		"/b.bin": new Uint8Array([6,0,7]),
		"/a/c.bin": "💩",
		// of dubious value but whatever
		"/b/d.bin": "\x08\0\x09",
	}
});
assert(ok);
assert.deepEqual(rom_data, new Uint8Array([
	1, 5, 6, 0, 7,
	240, 159, 146, 169,
	8, 0, 9]));

// ---------------------------

var {ok, rom_data} = Asar.patch({
	patch_name: "/a.asm",
	rom_data: new Uint8Array(),
	memory_files: {
		"/a.asm": "err or\nbgfdgfhd"
	}
});
assert(!ok);
assert.equal(rom_data, null);
assert.deepEqual(Asar.geterrors().map(e => e.errname), ['Eunknown_command', 'Eunknown_command']);

console.log("All checks ok!");
